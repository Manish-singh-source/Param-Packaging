function h($value) {
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

function findPageByKey($pages, $key) {
    foreach ($pages as $page) {
        if ($page['key'] === $key) {
            return $page;
        }
    }
    return null;
}

function getWordPressPageBySlug($slug) {
    if (!function_exists('mysqli_connect')) {
        return null;
    }

    $mysqli = @mysqli_connect('localhost', 'root', '', 'parampackaging_local');
    if (!$mysqli) {
        return null;
    }

    mysqli_set_charset($mysqli, 'utf8mb4');
    $sql = "SELECT p.ID, p.post_title, p.post_content, file.meta_value AS attached_file
            FROM wp_posts p
            LEFT JOIN wp_postmeta thumb ON p.ID = thumb.post_id AND thumb.meta_key = '_thumbnail_id'
            LEFT JOIN wp_postmeta file ON file.post_id = thumb.meta_value AND file.meta_key = '_wp_attached_file'
            WHERE p.post_type = 'page' AND p.post_status = 'publish' AND p.post_name = ?
            LIMIT 1";
    $stmt = mysqli_prepare($mysqli, $sql);
    if (!$stmt) {
        mysqli_close($mysqli);
        return null;
    }

    mysqli_stmt_bind_param($stmt, 's', $slug);
    mysqli_stmt_execute($stmt);
    $page = null;

    if (function_exists('mysqli_stmt_get_result')) {
        $result = mysqli_stmt_get_result($stmt);
        $page = $result ? mysqli_fetch_assoc($result) : null;
    } else {
        mysqli_stmt_bind_result($stmt, $id, $title, $content, $attachedFile);
        if (mysqli_stmt_fetch($stmt)) {
            $page = [
                'ID' => $id,
                'post_title' => $title,
                'post_content' => $content,
                'attached_file' => $attachedFile,
            ];
        }
    }

    mysqli_stmt_close($stmt);
    mysqli_close($mysqli);

    if (!$page) {
        return null;
    }

    $page['image_url'] = $page['attached_file']
        ? '/well-known/wp-content/uploads/' . ltrim($page['attached_file'], '/')
        : '';

    return $page;
}

function localizeWordPressContent($content) {
    return str_replace(
        [
            'https://parampackaging.com/wp-content/',
            'http://parampackaging.com/wp-content/',
        ],
        [
            '/well-known/wp-content/',
            '/well-known/wp-content/',
        ],
        (string) $content
    );
}
